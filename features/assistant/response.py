from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any, Iterable

import discord

from core.ai import split_text

# Only people explicitly tagged by the requesting user are allowed to be pinged.
# A name invented by Gemini must never become a Discord mention.
MENTION_ID_RE = re.compile(r"<@!?(\d{1,20})>")
NAME_END = r"(?![\w])"


@dataclass(frozen=True)
class ConversationDelivery:
    last_message: Any
    message_ids: tuple[int, ...]


def format_authorized_mentions(
    content: str,
    mentioned_people: Iterable[tuple[int, str]] = (),
) -> tuple[str, list[discord.Object]]:
    """Convert @Display Name to a real <@user_id> only for trusted Discord mentions.

    Refuse ambiguous aliases and never grant the model @everyone, role, or
    arbitrary user pings. This also handles raw <@id> strings generated by AI.
    """
    approved = {}
    for user_id, name in list(mentioned_people)[:6]:
        if not isinstance(user_id, int) or not 0 < user_id < 10**20:
            continue
        clean = str(name or "").strip()
        if not clean or len(clean) > 80 or "\n" in clean or "\r" in clean:
            continue
        approved[user_id] = clean

    # Identical display names are ambiguous; avoid tagging a random person.
    grouped: dict[str, list[int]] = {}
    for user_id, name in approved.items():
        grouped.setdefault(name.casefold(), []).append(user_id)
    unique = {
        user_id: name for user_id, name in approved.items()
        if len(grouped[name.casefold()]) == 1
    }

    # Do not convert arbitrary IDs generated by the model into active mentions.
    # Zero-width space breaks the Discord mention syntax while keeping it legible.
    def sanitize_raw(match):
        user_id = int(match.group(1))
        if user_id in unique:
            return f"<@{user_id}>"
        return f"<@\u200b{user_id}>"

    output = MENTION_ID_RE.sub(sanitize_raw, content or "")
    used: set[int] = set()
    # Longest aliases first to avoid @Ann consuming the prefix of @Anna.
    for user_id, name in sorted(unique.items(), key=lambda entry: len(entry[1]), reverse=True):
        pattern = re.compile(rf"(?<![\w@])@{re.escape(name)}{NAME_END}", re.IGNORECASE)
        output, count = pattern.subn(lambda _m, uid=user_id: f"<@{uid}>", output)
        if count or f"<@{user_id}>" in output:
            used.add(user_id)

    # A synthetic @everyone/@here from Gemini remains harmless.
    return output, [discord.Object(id=user_id) for user_id in sorted(used)]


async def send_conversation_reply(
    message,
    text: str,
    *,
    mentioned_people: Iterable[tuple[int, str]] = (),
) -> ConversationDelivery:
    # Resolve mentions before chunking so Discord tokens cannot be split across
    # message boundaries. The allowlist is reused on follow-up chunks.
    rendered, authorized_users = format_authorized_mentions(text or "", mentioned_people)
    chunks = split_text(rendered.strip(), limit=1900)
    if not chunks:
        chunks = ["Mình chưa tạo được câu trả lời cho tin nhắn này."]

    allowed = discord.AllowedMentions(
        everyone=False, roles=False, users=authorized_users, replied_user=False,
    )
    sent_messages = []
    sent = await message.reply(chunks[0], mention_author=False, allowed_mentions=allowed)
    sent_messages.append(sent)

    for chunk in chunks[1:]:
        sent = await message.channel.send(chunk, allowed_mentions=allowed)
        sent_messages.append(sent)

    return ConversationDelivery(
        last_message=sent,
        message_ids=tuple(
            int(item.id)
            for item in sent_messages
            if getattr(item, "id", None) is not None
        ),
    )
